// Package cssbuild builds the committed stylesheet `internal/web/static/app.css`
// by concatenating the parts under `internal/web/static_src/css` in the order
// their manifest lists them.
//
// The stylesheet is split for the reason the browser TypeScript is: one
// 6,800-line file has no section boundary anything can enforce, so a graph rule
// lands in the Markdown block and nothing notices. The parts restore that
// boundary, and the manifest keeps the cascade in one reviewable place.
//
// It concatenates rather than running the parts through a CSS bundler because
// the parts are the source of record and a bundler re-serializes them. esbuild
// in particular drops every explanatory comment and rewrites
// `[aria-busy='true']` to `[aria-busy=true]`: both are semantics-preserving and
// both make the artifact stop being readable as what was written. Byte-for-byte
// concatenation is also what lets the drift test compare generated output to its
// sources without normalizing anything, and what keeps this build free of Node —
// unlike `app.js`, regenerating the stylesheet needs no toolchain at all.
package cssbuild

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const (
	// SourceDir holds the stylesheet parts and their manifest, relative to the
	// repository root.
	SourceDir = "internal/web/static_src/css"

	// ManifestFile names the part list inside SourceDir.
	ManifestFile = "index.css"

	// OutputFile is the generated stylesheet, relative to the repository root.
	// It stays committed so a Go build and `go install` need no asset step.
	OutputFile = "internal/web/static/app.css"
)

const banner = "/* Generated by internal/web/cssbuild from " + SourceDir + "/" + ManifestFile + ". Do not edit; edit the parts. */\n\n"

var importLine = regexp.MustCompile(`^@import "([a-z0-9-]+\.css)";$`)

// Build returns the stylesheet bytes for the checkout at root without touching
// the filesystem beyond reading the sources.
func Build(root string) ([]byte, error) {
	dir := filepath.Join(root, filepath.FromSlash(SourceDir))
	parts, err := manifestParts(dir)
	if err != nil {
		return nil, err
	}
	if err := checkEveryPartImported(dir, parts); err != nil {
		return nil, err
	}

	var out bytes.Buffer
	out.WriteString(banner)
	for _, name := range parts {
		body, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, fmt.Errorf("cssbuild: read part %s: %w", name, err)
		}
		fmt.Fprintf(&out, "/* %s/%s */\n", SourceDir, name)
		out.Write(body)
	}
	return out.Bytes(), nil
}

// WriteBundle regenerates the committed stylesheet from its parts, and reports
// whether the bytes on disk changed.
//
// The write targets a fixed, tracked build artifact inside the caller's own
// source checkout, whose contents are a pure function of the sources sitting
// beside it. Nothing here reaches a vault, so no vault guarantee is in play; a
// regenerated file that is identical is not rewritten, which keeps `bn serve`
// from touching the artifact's mtime on every start.
//
//bn:direct-write regenerates a tracked build artifact in the source checkout, never vault content
func WriteBundle(root string) (bool, error) {
	want, err := Build(root)
	if err != nil {
		return false, err
	}

	path := filepath.Join(root, filepath.FromSlash(OutputFile))
	if got, err := os.ReadFile(path); err == nil && bytes.Equal(got, want) {
		return false, nil
	}
	if err := os.WriteFile(path, want, 0o644); err != nil {
		return false, fmt.Errorf("cssbuild: write %s: %w", OutputFile, err)
	}
	return true, nil
}

// manifestParts reads the manifest and returns the part names in cascade order.
// It is deliberately strict: the manifest is the only record of that order, so a
// line it cannot account for is an error rather than something to skip.
func manifestParts(dir string) ([]string, error) {
	data, err := os.ReadFile(filepath.Join(dir, ManifestFile))
	if err != nil {
		return nil, fmt.Errorf("cssbuild: read manifest: %w", err)
	}

	var (
		parts     []string
		seen      = map[string]bool{}
		inComment bool
	)
	for i, raw := range strings.Split(string(data), "\n") {
		line := strings.TrimSpace(raw)
		switch {
		case inComment:
			if strings.HasSuffix(line, "*/") {
				inComment = false
			}
			continue
		case line == "":
			continue
		case strings.HasPrefix(line, "/*"):
			if !strings.HasSuffix(line, "*/") {
				inComment = true
			}
			continue
		}

		match := importLine.FindStringSubmatch(line)
		if match == nil {
			return nil, fmt.Errorf(`cssbuild: %s:%d: expected @import "<part>.css";, got %q`, ManifestFile, i+1, line)
		}
		if seen[match[1]] {
			return nil, fmt.Errorf("cssbuild: %s:%d: %s is imported twice", ManifestFile, i+1, match[1])
		}
		seen[match[1]] = true
		parts = append(parts, match[1])
	}

	if inComment {
		return nil, fmt.Errorf("cssbuild: %s: unterminated comment", ManifestFile)
	}
	if len(parts) == 0 {
		return nil, fmt.Errorf("cssbuild: %s imports no parts", ManifestFile)
	}
	return parts, nil
}

// checkEveryPartImported fails when a part file exists but no import names it.
// Dropping it silently is the failure mode worth catching: the stylesheet still
// builds, so the only symptom is a page that renders unstyled.
func checkEveryPartImported(dir string, parts []string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("cssbuild: read %s: %w", SourceDir, err)
	}

	imported := make(map[string]bool, len(parts))
	for _, name := range parts {
		imported[name] = true
	}

	var orphans []string
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || name == ManifestFile || !strings.HasSuffix(name, ".css") {
			continue
		}
		if !imported[name] {
			orphans = append(orphans, name)
		}
	}
	if len(orphans) > 0 {
		return fmt.Errorf("cssbuild: %s does not import %s", ManifestFile, strings.Join(orphans, ", "))
	}
	return nil
}
